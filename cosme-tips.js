// 日替わりで1件選ぶ。登録中のコスメに関係するTipsを優先する
function cosmePickTip(activeCategories = [], dateStr = '') {
  const related = COSME_TIPS.filter(t => t.cat && activeCategories.includes(t.cat));
  const pool = related.length ? related : COSME_TIPS;
  // 日付文字列から安定した数値を作る（同じ日は同じTipsを表示）
  let n = 0;
  for (const ch of String(dateStr)) n = (n * 31 + ch.charCodeAt(0)) >>> 0;
  return pool[n % pool.length];
}
